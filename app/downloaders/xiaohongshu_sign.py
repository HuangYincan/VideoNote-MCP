def _mrc(e: str) -> int:
    o = -1

    def right_without_sign(num: int, bit: int = 0) -> int:
        val = ctypes.c_uint32(num).value >> bit
        max32 = 4294967295
        return (val + (max32 + 1)) % (2 * (max32 + 1)) - max32 - 1

    n_max = min(57, len(e))
    for n in range(n_max):
        o = _MRC_TABLE[(o & 255) ^ ord(e[n])] ^ right_without_sign(o, 8)
    return o ^ -1 ^ 3988292384


def _triplet_to_b64(e: int) -> str:
    return (
        _B64_LOOKUP[63 & (e >> 18)]
        + _B64_LOOKUP[63 & (e >> 12)]
        + _B64_LOOKUP[(e >> 6) & 63]
        + _B64_LOOKUP[e & 63]
    )


def _encode_chunk(e: list, t: int, r: int) -> str:
    m = []
    for b in range(t, r, 3):
        n = (16711680 & (e[b] << 16)) + ((e[b + 1] << 8) & 65280) + (e[b + 2] & 255)
        m.append(_triplet_to_b64(n))
    return "".join(m)


def _b64_encode(e: list) -> str:
    p = len(e)
    w = p % 3
    u = []
    z = 16383
    h = 0
    z_end = p - w
    while h < z_end:
        u.append(_encode_chunk(e, h, z_end if h + z > z_end else h + z))
        h += z
    if w == 1:
        f = e[p - 1]
        u.append(_B64_LOOKUP[f >> 2] + _B64_LOOKUP[(f << 4) & 63] + "==")
    elif w == 2:
        f = (e[p - 2] << 8) + e[p - 1]
        u.append(_B64_LOOKUP[f >> 10] + _B64_LOOKUP[63 & (f >> 4)] + _B64_LOOKUP[(f << 2) & 63] + "=")
    return "".join(u)


def _encode_utf8(e: str) -> list:
    b = []
    m = urllib.parse.quote(e, safe="~()*!.'")
    w = 0
    while w < len(m):
        t = m[w]
        if t == "%":
            b.append(int(m[w + 1] + m[w + 2], 16))
            w += 2
        else:
            b.append(ord(t[0]))
        w += 1
    return b
