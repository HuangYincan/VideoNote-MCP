def get_a1_and_web_id() -> tuple[str, str]:
    """生成本地 a1 / webId（设备指纹 cookie）。"""

    def random_str(length: int) -> str:
        alphabet = string.ascii_letters + string.digits
        return "".join(random.choice(alphabet) for _ in range(length))

    d = hex(int(time.time() * 1000))[2:] + random_str(30) + "5" + "0" + "000"
    g = (d + str(binascii.crc32(str(d).encode("utf-8"))))[:52]
    return g, hashlib.md5(g.encode("utf-8")).hexdigest()


def sign(uri: str, data=None, ctime: Optional[int] = None, a1: str = "", b1: str = "") -> dict:
    """计算 x-s / x-t / x-s-common。"""

    def _encode32(n: str) -> str:
        alphabet = "A4NjFqYu5wPHsO0XTdDgMa2r1ZQocVte9UJBvk6/7=yRnhISGKblCWi+LpfE8xzm3"
        out = ""
        for i in range(0, 32, 3):
            o = ord(n[i])
            g = ord(n[i + 1]) if i + 1 < 32 else 0
            h = ord(n[i + 2]) if i + 2 < 32 else 0
            x = ((o & 3) << 4) | (g >> 4)
            p = ((15 & g) << 2) | (h >> 6)
            v = o >> 2
            b = h & 63 if h else 64
            if not g:
                p = b = 64
            out += alphabet[v] + alphabet[x] + alphabet[p] + alphabet[b]
        return out

    ts = int(round(time.time() * 1000) if not ctime else ctime)
    payload = json.dumps(data, separators=(",", ":"), ensure_ascii=False) if isinstance(data, dict) else ""
    md5_str = hashlib.md5(f"{ts}test{uri}{payload}".encode("utf-8")).hexdigest()
    x_s = _encode32(md5_str)
    x_t = str(ts)
    common = {
        "s0": 5,
        "s1": "",
        "x0": "1",
        "x1": "3.2.0",
        "x2": "Windows",
        "x3": "xhs-pc-web",
        "x4": "2.3.1",
        "x5": a1,
        "x6": x_t,
        "x7": x_s,
        "x8": b1,
        "x9": _mrc(x_t + x_s),
        "x10": 1,
    }
    return {
        "x-s": x_s,
        "x-t": x_t,
        "x-s-common": _b64_encode(_encode_utf8(json.dumps(common, separators=(",", ":")))),
    }


